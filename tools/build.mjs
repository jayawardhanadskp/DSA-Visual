// Build step (only needed if you change lessons/data/*.js):
//   node tools/build.mjs
// 1. runs every visualizer's Python code through tools/tracer.py → lessons/data/*.traces.js
// 2. embeds tracer.py + workbook/_check.py for the browser → assets/py-src.js
// 3. writes the offline workbook (workbook/*.py) and checks every solution passes its tests
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import vm from 'node:vm'

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..')
const DATA = path.join(ROOT, 'lessons/data')
const only = process.argv[2] // optional: lesson number, e.g. "05"

const ctx = { console, localStorage: { getItem: () => null, setItem() {} } }
ctx.window = ctx
vm.createContext(ctx)
vm.runInContext(fs.readFileSync(path.join(ROOT, 'assets/core.js'), 'utf8'), ctx)
const DSA = ctx.DSA

const toPy = (v) => {
  if (v === null || v === undefined) return 'None'
  if (v === true) return 'True'
  if (v === false) return 'False'
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : v > 0 ? 'float("inf")' : 'float("-inf")'
  if (typeof v === 'string') return JSON.stringify(v)
  if (Array.isArray(v)) return '[' + v.map(toPy).join(', ') + ']'
  if (v.__py__) return '{"__py__": ' + JSON.stringify(v.__py__) + '}'
  return '{' + Object.entries(v).map(([k, x]) => JSON.stringify(k) + ': ' + toPy(x)).join(', ') + '}'
}
const htmlToText = (h) =>
  h
    .replace(/<\/(p|li|div|h\d)>/g, '\n')
    .replace(/<li>/g, '  • ')
    .replace(/<br\s*\/?>/g, '\n')
    .replace(/<[^>]+>/g, '')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&amp;/g, '&')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&nbsp;/g, ' ')
    .split('\n')
    .map((l) => l.trim())
    .filter(Boolean)
const wrap = (line, width = 92) => {
  const out = []
  let cur = ''
  for (const word of line.split(' ')) {
    if ((cur + ' ' + word).trim().length > width) {
      out.push(cur)
      cur = word
    } else cur = (cur + ' ' + word).trim()
  }
  if (cur) out.push(cur)
  return out
}

let failures = 0
const files = fs.readdirSync(DATA).filter((f) => /^\d\d-.*\.js$/.test(f) && !f.endsWith('.traces.js')).sort()

for (const file of files) {
  const num = file.slice(0, 2)
  if (only && num !== only) continue
  const before = { viz: new Set(Object.keys(DSA.viz)), problems: new Set(Object.keys(DSA.problems)) }
  vm.runInContext(fs.readFileSync(path.join(DATA, file), 'utf8'), ctx, { filename: file })
  const vizIds = Object.keys(DSA.viz).filter((k) => !before.viz.has(k))
  const probIds = Object.keys(DSA.problems).filter((k) => !before.problems.has(k))

  // 1. traces
  const traces = {}
  for (const id of vizIds) {
    const def = DSA.viz[id]
    const json = execFileSync('python3', [path.join(ROOT, 'tools/tracer.py'), String(def.maxSteps || 1000)], { input: def.code, maxBuffer: 1 << 28 }).toString()
    const t = JSON.parse(json)
    if (t.error && !def.expectError) {
      console.log(`  ❌ viz ${id}: ${t.error}`)
      failures++
    }
    if (t.truncated) console.log(`  ⚠️  viz ${id}: truncated at ${t.steps.length} steps`)
    traces[id] = t
  }
  const tracePath = path.join(DATA, file.replace(/\.js$/, '.traces.js'))
  if (vizIds.length) {
    fs.writeFileSync(tracePath, '// generated by tools/build.mjs — do not edit\naddTraces(' + JSON.stringify(traces) + ')\n')
  } else if (fs.existsSync(tracePath)) fs.unlinkSync(tracePath)
  const kb = vizIds.length ? Math.round(fs.statSync(tracePath).size / 1024) : 0

  // 2. workbook
  if (probIds.length) {
    const lesson = DSA.COURSE.find((l) => l.id === num)
    const base = file.replace(/\.js$/, '').replace(/-/g, '_')
    const header = (sol) => `"""
Lesson ${num} · ${lesson ? lesson.title : ''} — ${sol ? 'SOLUTIONS' : 'workbook'}
The visual lesson: lessons/${file.replace(/\.js$/, '.html')}

${sol ? "Only open this after you've really tried (15+ minutes per problem)." : `How to use:
  1. Write your code inside each function (replace the \`pass\` / TODO lines).
  2. Run:  python3 workbook/${base}.py
  3. Fix until every problem shows ✅. Use print() freely while debugging.`}
"""
from _check import check, ListNode, TreeNode  # noqa: F401  (helpers for linked-list / tree problems)
`
    const body = (sol) =>
      probIds
        .map((pid, i) => {
          const p = DSA.problems[pid]
          const lines = [
            `# ${'─'.repeat(88)}`,
            `# ${i + 1}. ${p.title}  ·  ${p.level}${p.pattern ? '  ·  ' + p.pattern : ''}`,
            '#',
            ...htmlToText(p.prompt).flatMap((l) => wrap(l)).map((l) => '# ' + l),
            ...(p.leetcode ? ['#', `# LeetCode: ${p.leetcode}`] : []),
            `# ${'─'.repeat(88)}`,
          ]
          return lines.join('\n') + '\n' + (sol ? p.solution : p.starter) + '\n'
        })
        .join('\n\n')
    const main =
      '\n\nif __name__ == "__main__":\n' +
      probIds
        .map((pid) => {
          const p = DSA.problems[pid]
          const name = p.fn
          const opts = []
          if (p.compare && p.compare !== 'exact') opts.push(`compare=${JSON.stringify(p.compare)}`)
          if (p.convert) opts.push(`convert=${toPy(p.convert)}`)
          if (p.inplace !== undefined && p.inplace !== null) opts.push(`inplace=${p.inplace}`)
          const tests = '[\n' + p.tests.map((t) => '        ' + toPy(t) + ',').join('\n') + '\n    ]'
          return `    check(${name}, ${tests}${opts.length ? ', ' + opts.join(', ') : ''})`
        })
        .join('\n')
    const wbPath = path.join(ROOT, 'workbook', base + '.py')
    const solPath = path.join(ROOT, 'workbook/solutions', base + '.py')
    fs.writeFileSync(wbPath, header(false) + '\n\n' + body(false) + main + '\n')
    fs.writeFileSync(solPath, header(true) + '\n\n' + body(true) + main + '\n')
    fs.copyFileSync(path.join(ROOT, 'workbook/_check.py'), path.join(ROOT, 'workbook/solutions/_check.py'))
    // every solution must pass
    const out = execFileSync('python3', [solPath], { cwd: path.join(ROOT, 'workbook/solutions'), env: { ...process.env, PYTHONDONTWRITEBYTECODE: '1' } }).toString()
    const bad = out.split('\n').filter((l) => /❌|🟨|⬜/.test(l))
    if (bad.length) {
      failures++
      console.log(`  ❌ solutions ${base}:\n` + out)
    }
    // starters must at least load (no syntax errors)
    try {
      execFileSync('python3', ['-c', `import ast,sys; ast.parse(open(sys.argv[1]).read())`, wbPath])
    } catch (e) {
      failures++
      console.log(`  ❌ starter file ${base} has a syntax error`)
    }
  }
  console.log(`${file}: ${vizIds.length} visualizers (${kb} KB), ${probIds.length} problems`)
}

// 3. Python sources for the browser
const src = {
  tracer: fs.readFileSync(path.join(ROOT, 'tools/tracer.py'), 'utf8'),
  check: fs.readFileSync(path.join(ROOT, 'workbook/_check.py'), 'utf8'),
}
fs.writeFileSync(path.join(ROOT, 'assets/py-src.js'), '// generated by tools/build.mjs — do not edit\nDSA.PY_SRC = ' + JSON.stringify(src) + '\n')

if (failures) {
  console.log(`\n${failures} problem(s) found`)
  process.exit(1)
}
console.log('\n✅ build ok')
